import datetime

def get_report_files(reports_dir='reports'):
    """
    Scans the reports directory, groups files, and extracts metadata (dates).
    """
    if not os.path.exists(reports_dir):
        return {}
    
    files = os.listdir(reports_dir)
    report_data = []
    
    for f in files:
        path = os.path.join(reports_dir, f)
        if not os.path.isfile(path): continue
        
        # Extract date
        dt = None
        category = "Other"
        
        # Pattern 1: authority_report_Low_20260214-233459.csv
        date_match = re.search(r'(\d{8})-(\d{6})', f)
        if date_match:
            try:
                dt = datetime.datetime.strptime(date_match.group(1), '%Y%m%d').date()
            except: pass
            
        # Pattern 2: SAR-1771077750-784.txt
        if not dt:
            sar_match = re.search(r'SAR-(\d+)', f)
            if sar_match:
                try:
                    dt = datetime.datetime.fromtimestamp(int(sar_match.group(1))).date()
                except: pass
        
        # Fallback to file mtime if no date in name
        if not dt:
            dt = datetime.datetime.fromtimestamp(os.path.getmtime(path)).date()

        # Grouping
        if f.startswith('SAR-'): category = "SAR Reports"
        elif f.startswith('authority_alert_') or f.startswith('authority_report_'): 
            category = "Authority Correspondence"
        
        report_data.append({
            'filename': f,
            'category': category,
            'date': dt,
            'size': os.path.getsize(path)
        })
        
    return pd.DataFrame(report_data)

def render_report_explorer(reports_dir='reports'):
    """
    Renders the simplified report explorer UI.
    """
    st.markdown("## 📂 Forensic Report Explorer")
    
    df_reports = get_report_files(reports_dir)
    if df_reports.empty:
        st.info("No reports found in the system.")
        return

    # Top Controls for Filtering
    with st.container(border=True):
        col1, col2 = st.columns([1, 1])
        with col1:
            min_date = df_reports['date'].min()
            max_date = df_reports['date'].max()
            date_range = st.date_input("Date Range", value=(min_date, max_date), min_value=min_date, max_value=max_date)
        with col2:
            search = st.text_input("Search Reports", placeholder="e.g. SAR-1771 or Merchant...")

    # Apply Filters
    df_filtered = df_reports.copy()
    if len(date_range) == 2:
        start_date, end_date = date_range
        mask = (df_filtered['date'] >= start_date) & (df_filtered['date'] <= end_date)
        df_filtered = df_filtered[mask]
        
    if search:
        df_filtered = df_filtered[df_filtered['filename'].str.contains(search, case=False)]

    # Batch Analysis View (Default/Unified)
    render_batch_analysis(df_filtered, reports_dir)


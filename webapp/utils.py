def render_file_preview(reports_dir, filename):
    file_path = os.path.join(reports_dir, filename)
    file_ext = os.path.splitext(filename)[1].lower()
    
    st.markdown(f"### 📄 Preview: {filename}")
    try:
        if file_ext == '.txt':
            with open(file_path, 'r') as f:
                content = f.read()
            st.markdown(f"```text\n{content}\n```")
            st.download_button("Download TXT", content, file_name=filename)
        elif file_ext == '.csv':
            df = pd.read_csv(file_path)
            st.dataframe(df, use_container_width=True)
            csv_bytes = df.to_csv(index=False).encode('utf-8')
            st.download_button("Download CSV", csv_bytes, file_name=filename, mime='text/csv')
    except Exception as e:
        st.error(f"Error previewing: {e}")

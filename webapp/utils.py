def style_dataframe_rows(df, threshold):
    """
    Applies styling to dataframe rows based on risk score.
    Returns a Styler object.
    """
    def highlight_risk(row):
        try:
            p = float(row.get('proba', 0))
            if p >= threshold:
                return ['background-color: rgba(251, 113, 133, 0.15); color: #fecdd3'] * len(row)
        except:
            pass
        return [''] * len(row)

    return df.style.apply(highlight_risk, axis=1).format({'proba': '{:.4f}', 'amt': '${:.2f}'})


